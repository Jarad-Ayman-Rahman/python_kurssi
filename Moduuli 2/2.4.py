
luku1 = int(input("Eka kokonaisluku"))
luku2 = int(input("toka kokonaisluku"))
luku3 = int(input("kolmas kokonaisluku"))

summa = luku1 + luku2 + luku3
tulo = luku1 * luku2 * luku3
keskiarvo = summa / 3

input(f"lukujen summa on {summa}  ")
input(f"lukujen tulo on {tulo}  ")
input(f"lukuje keskiarvo on {keskiarvo}  ")